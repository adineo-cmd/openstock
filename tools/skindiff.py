#!/usr/bin/env python3
import json
import sys
from itertools import combinations
from pathlib import Path

RELATIVE_MOTION_TOLERANCE = 0.20


def load(tokens_dir: Path, name: str) -> dict:
    path = tokens_dir / f"{name}.json"
    if not path.exists():
        raise SystemExit(f"FAIL: unknown skin {name!r} (no {path})")
    return json.loads(path.read_text(encoding="utf-8"))


def flatten(data: dict, prefix: str = "") -> dict[str, object]:
    out: dict[str, object] = {}
    for key, value in data.items():
        path_key = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict):
            out.update(flatten(value, path_key))
        else:
            out[path_key] = value
    return out


BEHAVIORAL = {
    "panel.expandMode", "panel.compactStop", "panel.fullThreshold", "panel.openThreshold",
    "panel.contentAnchor", "panel.statusBarVisible",
    "layout.columns", "layout.tilesAreCircles", "layout.tileLabel",
    "motion.type", "motion.damping", "motion.easing",
}


def classify(path_key: str, a: object, b: object) -> str:
    if path_key in BEHAVIORAL:
        return "behavior"
    if path_key == "motion.durationMs":
        try:
            if abs(float(a) - float(b)) / max(float(a), float(b), 1) > RELATIVE_MOTION_TOLERANCE:
                return "behavior"
        except (TypeError, ValueError):
            return "behavior"
        return "look"
    if path_key == "layout.tileSizeDp":
        threshold = 44
        return "behavior" if (float(a) >= threshold) != (float(b) >= threshold) else "look"
    return "look"


def diff(a_name: str, a: dict, b_name: str, b: dict) -> dict[str, list]:
    fa, fb = flatten(a), flatten(b)
    keys = sorted(set(fa) | set(fb) - {"skin", "specRefs", "desc"})
    report: dict[str, list] = {"behavior": [], "look": [], "same": []}
    for key in keys:
        if key in ("skin", "specRefs", "desc"):
            continue
        va, vb = fa.get(key, "<missing>"), fb.get(key, "<missing>")
        if va == vb:
            report["same"].append(key)
        else:
            report[classify(key, va, vb)].append((key, va, vb))
    return report


def render(a_name: str, a: dict, b_name: str, b: dict) -> str:
    rep = diff(a_name, a, b_name, b)
    lines = [
        f"# skindiff: `{a_name}` vs `{b_name}`",
        "",
        f"**{len(rep['behavior'])} behavioral deltas · {len(rep['look'])} look deltas · "
        f"{len(rep['same'])} dimensions identical**",
        "",
        "A behavioral delta changes how the panel *interacts* (stages, thresholds, motion,",
        "grid structure); a look delta only changes what you see. Generated by",
        "`tools/skindiff.py` from `specs/tokens/*.json` — do not edit by hand.",
        "",
    ]
    if rep["behavior"]:
        lines += ["## Behavioral", "", "| Dimension | " + a_name + " | " + b_name + " |", "|---|---|---|"]
        for key, va, vb in rep["behavior"]:
            lines.append(f"| `{key}` | `{va}` | `{vb}` |")
        lines.append("")
    if rep["look"]:
        lines += ["## Look", "", "| Dimension | " + a_name + " | " + b_name + " |", "|---|---|---|"]
        for key, va, vb in rep["look"]:
            lines.append(f"| `{key}` | `{va}` | `{vb}` |")
        lines.append("")
    if rep["same"]:
        lines += ["## Identical", "", ", ".join(f"`{k}`" for k in rep["same"]), ""]
    return "\n".join(lines)


def main() -> int:
    args = sys.argv[1:]
    repo = Path(__file__).resolve().parent.parent
    tokens_dir = repo / "specs" / "tokens"
    out_dir = None
    check = None
    all_pairs = False
    names: list[str] = []

    i = 0
    while i < len(args):
        arg = args[i]
        if arg == "--all":
            all_pairs = True
            names = sorted(p.stem for p in tokens_dir.glob("*.json"))
        elif arg == "--out-dir":
            i += 1
            out_dir = Path(args[i])
        elif arg == "--check":
            i += 1
            check = Path(args[i])
        else:
            names.append(arg)
        i += 1

    if check is not None:
        if len(names) != 2:
            print("usage: skindiff.py a b --check path.md", file=sys.stderr)
            return 1
        a, b = names
        expected = render(a, load(tokens_dir, a), b, load(tokens_dir, b))
        if not check.exists() or check.read_text(encoding="utf-8") != expected:
            print(f"FAIL: {check} is stale — regenerate with skindiff.py --all --out-dir docs/diffs")
            return 1
        print(f"PASS: {check} up to date")
        return 0

    if not all_pairs and len(names) != 2:
        print("usage: skindiff.py <skinA> <skinB> | --all --out-dir DIR", file=sys.stderr)
        return 1

    pairs = list(combinations(names, 2)) if all_pairs else [(names[0], names[1])]
    for a, b in pairs:
        report = render(a, load(tokens_dir, a), b, load(tokens_dir, b))
        if out_dir is not None:
            out_dir.mkdir(parents=True, exist_ok=True)
            target = out_dir / f"{a}-vs-{b}.md"
            target.write_text(report, encoding="utf-8")
            print(f"wrote {target}")
        else:
            print(report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
